// Dev helper (v0.6): cargo market, route editor and a combination airline's network.
import { _electron as electron } from '@playwright/test';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const [dir] = process.argv.slice(2);
const app = await electron.launch({ args: [join(import.meta.dirname, '..', 'out', 'main', 'index.js')], env: { ...process.env, SKYEMPIRE_USER_DATA: mkdtempSync(join(tmpdir(), 'se-shot-')) } });
const win = await app.firstWindow();
await win.setViewportSize({ width: 1440, height: 900 });
await win.getByRole('button', { name: 'New career' }).click();
await win.getByLabel('Airline name').fill('Hanse Cargo');
await win.getByRole('button', { name: 'Choose a hub' }).click();
await win.getByLabel('Search airports').fill('FRA');
await win.keyboard.press('Enter');
await win.getByRole('button', { name: 'Choose difficulty' }).click();
await win.getByRole('radio', { name: /Passenger \+ Cargo/ }).click();
await win.screenshot({ path: join(dir, 'cargo-newairline.png') });
await win.getByRole('button', { name: 'Found airline' }).click();
await win.getByRole('button', { name: 'Skip tutorial' }).click();
await win.keyboard.press('3');
await win.getByRole('button', { name: 'Get aircraft' }).click();
await win.getByRole('combobox', { name: 'Type' }).selectOption('freighter');
await win.waitForTimeout(800);
await win.screenshot({ path: join(dir, 'cargo-market.png') });
await win.locator('article').filter({ hasText: 'ATR 72-600F' }).first().getByRole('button', { name: /^Lease for/ }).click();
await win.getByRole('dialog').getByRole('button', { name: /^Lease for/ }).click();
await win.getByRole('button', { name: 'Close market' }).click();
await win.keyboard.press('2');
await win.keyboard.press('n');
await win.getByRole('radio', { name: 'Cargo' }).click();
await win.getByRole('combobox', { name: 'To', exact: true }).fill('LEJ');
await win.keyboard.press('Enter');
await win.waitForTimeout(1500);
await win.screenshot({ path: join(dir, 'cargo-editor.png') });
await app.close();
