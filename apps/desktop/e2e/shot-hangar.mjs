// Dev helper (v0.3): aircraft market with photos, the aircraft page, the cabin editor and the update banner.
import { _electron as electron } from '@playwright/test';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const [dir] = process.argv.slice(2);
const app = await electron.launch({ args: [join(import.meta.dirname, '..', 'out', 'main', 'index.js')], env: { ...process.env, SKYEMPIRE_USER_DATA: mkdtempSync(join(tmpdir(), 'se-shot-')) } });
const win = await app.firstWindow();
win.on('pageerror', (e) => console.log('[pageerror]', e.message));
win.on('response', (r) => r.status() === 404 && console.log('[404]', r.url()));
await win.setViewportSize({ width: 1440, height: 900 });
await win.evaluate(async () => {
  await window.game.newGame({ seed: 4, regionId: 'world', difficulty: 'normal', homeBaseId: 'DEL', airline: { name: 'Saffron Air', code: 'S4F', colors: { primary: '#e08a1e', secondary: '#ffffff' }, logoShape: 'circle' } });
  await window.game.command({ type: 'leaseAircraft', typeId: 'A20N', cabin: { economy: 174, premium: 0, business: 8 } });
});
await win.reload();
await win.waitForTimeout(1200);
await win.keyboard.press('3');
await win.getByRole('button', { name: 'Get aircraft' }).click();
await win.waitForTimeout(1200);
await win.screenshot({ path: join(dir, 'market.png') });
await win.locator('article').filter({ hasText: 'Boeing 787-9' }).getByRole('button', { name: 'Details' }).click();
await win.waitForTimeout(800);
await win.screenshot({ path: join(dir, 'details.png') });
await win.getByRole('tab', { name: 'Three class' }).click();
await win.getByRole('dialog').evaluate((d) => d.scrollTo(0, d.scrollHeight));
await win.waitForTimeout(400);
await win.screenshot({ path: join(dir, 'details-cabin.png') });
await win.getByRole('button', { name: 'Close', exact: true }).first().click();
await win.waitForTimeout(300);
await win.locator('article').filter({ hasText: 'Airbus A320neo' }).getByRole('button', { name: /^Lease for/ }).click();
await win.getByRole('dialog').getByRole('button', { name: 'Two class' }).click();
await win.waitForTimeout(400);
await win.screenshot({ path: join(dir, 'cabin-editor.png') });
await win.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click();
await win.waitForTimeout(300);
await win.getByRole('button', { name: 'Close market' }).click();
// Pretend a release is out (sends the same message the updater sends).
const send = (s) => app.evaluate(({ BrowserWindow }, s) => BrowserWindow.getAllWindows()[0].webContents.send('update:state', s), s);
const base = { current: await app.evaluate(({ app }) => app.getVersion()), version: '0.4.0', canInstall: true, url: 'https://github.com/saurabhwebdev/skyempire/releases/latest', notes: '- **Example** release notes' };
await send({ ...base, status: 'available' });
await win.waitForTimeout(600);
await win.screenshot({ path: join(dir, 'update-available.png') });
await send({ ...base, status: 'downloading', percent: 64 });
await win.waitForTimeout(400);
await win.screenshot({ path: join(dir, 'update-downloading.png') });
await send({ ...base, status: 'ready', percent: 100 });
await win.waitForTimeout(400);
await win.screenshot({ path: join(dir, 'update-ready.png') });
await app.close();
